import { pathToFileURL } from 'node:url';

// Keep this generator path for the existing Grafana check 91182. It changes
// only the k6 script; the check's probe, interval and alerting stay unchanged.
export function renderGrafanaScheduleCheck() {
  return `// Generated by: node ops/academy/grafana-schedule-check.mjs
// Update the existing Academy check. One Frankfurt probe every 600 seconds.
import http from 'k6/http';
import { check, fail } from 'k6';

const URL = 'https://compass.dynaminds.pl/api/akademia/health';

export default function () {
  let result = 'academy_health_unavailable';
  try {
    const response = http.get(URL, {
      headers: { 'User-Agent': 'compass-academy-synthetic/1.0' },
      timeout: '10s',
    });
    if (typeof response.body !== 'string' || response.body.length === 0 ||
        response.body.length > 128) throw new Error('invalid_response');
    const data = JSON.parse(response.body);
    if (!data || typeof data !== 'object' || Array.isArray(data) ||
        Object.keys(data).length !== 1 ||
        !['healthy', 'degraded', 'unhealthy'].includes(data.status) ||
        response.status !== (data.status === 'unhealthy' ? 503 : 200)) {
      throw new Error('invalid_response');
    }
    result = data.status === 'healthy' ? 'healthy' : 'academy_' + data.status;
  } catch {
    // Never print the response body, transport error or request headers.
    result = 'academy_health_unavailable';
  }
  const passed = check(result, {
    'Academy operational health is healthy': (value) => value === 'healthy',
  });
  // Synthetic Monitoring ignores k6 thresholds; fail() marks the probe failed.
  if (!passed) fail(result);
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.stdout.write(renderGrafanaScheduleCheck());
}
