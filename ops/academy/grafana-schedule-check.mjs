import { pathToFileURL } from 'node:url';
import { MAX_AGE_MS, MAX_INPUT_BYTES, auditWatchdogSchedule } from './watchdog-schedule-audit.mjs';

// Grafana's editor accepts a single k6 script, not a local Node module import.
// Embed the existing, tested validator so the external check uses the same policy.
export function renderGrafanaScheduleCheck() {
  return `// Generated by: node ops/academy/grafana-schedule-check.mjs
// Paste this entire script into a Grafana Synthetic Monitoring k6 scripted check.
import http from 'k6/http';
import { check, fail } from 'k6';

const URL = 'https://api.github.com/repos/B2B-net-S-A/COMPASS/actions/workflows/academy-health.yml/runs?event=schedule&per_page=1';
const MAX_INPUT_BYTES = ${MAX_INPUT_BYTES};
const MAX_AGE_MS = ${MAX_AGE_MS};

${auditWatchdogSchedule.toString()}

export default function () {
  let report = { status: 'unhealthy', code: 'run_metadata_unavailable' };
  try {
    const response = http.get(URL, {
      headers: {
        Accept: 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'compass-academy-synthetic/1.0',
      },
      timeout: '10s',
    });
    if (response.status !== 200 || typeof response.body !== 'string' ||
        response.body.length === 0 || response.body.length > MAX_INPUT_BYTES) {
      throw new Error('run_metadata_unavailable');
    }
    report = auditWatchdogSchedule(JSON.parse(response.body));
  } catch {
    // Never print the response body, transport error or request headers.
    report = { status: 'unhealthy', code: 'run_metadata_unavailable' };
  }
  const passed = check(report, {
    'Academy scheduled watchdog has a successful run within 30 minutes':
      (result) => result.status === 'healthy',
  });
  // Synthetic Monitoring ignores k6 thresholds. A failed check() emits a
  // metric; fail() also aborts this iteration so the probe reports failure.
  if (!passed) fail('academy_schedule_check=' + report.code);
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.stdout.write(renderGrafanaScheduleCheck());
}
